require('dotenv').config();
const express = require('express');
const cors = require('cors');
const { GoogleGenerativeAI } = require('@google/generative-ai');

const app = express();
app.use(cors());
app.use(express.json());

// Ключ безопасно подтягивается из скрытых настроек Render
const genAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY);

app.post('/api/humanize', async (req, res) => {
    try {
        const model = genAI.getGenerativeModel({ 
            model: "gemini-3.6-flash",
            generationConfig: {
                temperature: 0.85, // Подняли для непредсказуемости текста
                topP: 0.95,
            }
        });

        const prompt = `Перепиши следующий текст так, чтобы он гарантированно прошел проверку детекторами ИИ как текст, написанный живым человеком-экспертом. 
        
        Твоя задача — уйти от "сглаженной структуры" и идеального академического слога, добавив естественные человеческие шероховатости, сохраняя при этом научный смысл.

        Соблюдай эти критические правила:
        1. Асимметрия: Делай абзацы разной длины (один очень короткий, следующий длинный). 
        2. Рваный ритм (Burstiness): Чередуй сложные предложения с короткими, рублеными фразами (из 3-5 слов). Избегай идеального перетекания одной мысли в другую.
        3. Живой язык: Снизь уровень "канцелярита". Используй профессиональные термины, но связывай их простыми, повседневными словами. Текст должен звучать как рассуждение реального исследователя, а не как сухой отчет.
        4. Исключи маркеры ИИ и "воду": категорически запрещено использовать вводные конструкции ("таким образом", "в свою очередь", "как известно", "следует отметить"). Начинай предложения сразу с сути.
        5. Научная точность: Строго сохраняй в неизменном виде все физические законы, формулы, единицы измерения и данные.
        
        Текст для обработки: ${req.body.text}`;

        const result = await model.generateContent(prompt);
        res.json({ result: result.response.text() });
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
});

app.listen(3000, () => console.log('Сервер запущен на порту 3000'));
