require('dotenv').config();
const express = require('express');
const cors = require('cors');
const { GoogleGenerativeAI } = require('@google/generative-ai');

const app = express();
app.use(cors());
app.use(express.json());

// Ключ безопасно подтягивается из скрытых настроек Render
const genAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY);

app.post('/api/humanize', async (req, res) => {
    try {
        const model = genAI.getGenerativeModel({ 
            model: "gemini-3.6-flash",
            generationConfig: {
                temperature: 0.85, // Подняли для непредсказуемости текста
                topP: 0.95,
            }
        });

        const prompt = `Перепиши следующий текст так, чтобы он идеально подходил для официальной школьной исследовательской работы или методического пособия, и при этом гарантированно проходил проверки на ИИ-генерацию (антиплагиат) как текст, написанный живым человеком.

        Твоя задача — объединить строгий научный стиль и "человеческую" непредсказуемость.

        Правила стиля (Академичность):
        1. Используй строгую научно-педагогическую терминологию (например: "эмпирические данные", "деятельностный подход", "образовательный стандарт", "целесообразно").
        2. Полностью исключи разговорные слова, сленг, эмоциональную окраску, публицистический стиль и обращения к читателю.
        3. Сохраняй научную точность: физические законы, формулы, единицы измерения и данные должны оставаться неизменными.

        Правила обхода антиплагиата (Человечность):
        4. Асимметрия и ритм (Burstiness): Строго чередуй длинные, сложноподчиненные предложения с короткими и емкими (из 4-6 слов). Текст не должен быть монотонным.
        5. Структура: Делай абзацы разной длины. Избегай идеального, симметричного перетекания одной мысли в другую, свойственного машинам.
        6. Исключи маркеры ИИ: категорически запрещено использовать типичные вводные конструкции нейросетей ("важно отметить", "таким образом", "в заключение", "в современном мире", "безусловно", "как известно").

        Текст для обработки: ${req.body.text}`;

        const result = await model.generateContent(prompt);
        res.json({ result: result.response.text() });
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
});

app.listen(3000, () => console.log('Сервер запущен на порту 3000'));
